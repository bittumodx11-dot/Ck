/**
 * Apply a template's visual styling to user's data while strictly preserving
 * ALL personal details, educations, experiences, family fields, photos, custom sections, etc.
 */
export function applyTemplateToData(
  current: BiodataData,
  templateId: string
): BiodataData {
  const tpl = BIODATA_TEMPLATES.find((t) => t.id === templateId);
  if (!tpl) return current;

  return {
    ...current,
    template: tpl.id,
    fontFamily: tpl.fontFamily,
    fontScale: tpl.fontScale || current.fontScale,
    sectionTitleColor: tpl.sectionTitleColor,
    bodyTextColor: tpl.bodyTextColor,
    accentColor: tpl.accentColor,
    backgroundColor: tpl.backgroundColor,
    sectionTitleStyle: tpl.sectionTitleStyle,
    titleColor: tpl.primaryColor,
    headerLayout: tpl.headerLayout,
    headerStyle: tpl.headerStyle,
    borderStyle: tpl.borderStyle,
    infoLayoutStyle: tpl.infoLayoutStyle,
    photoShape: tpl.photoShape,
    photoBorder: tpl.photoBorder,
    photoBorderColor: tpl.photoBorderColor,
    sacredHeader: tpl.sacredHeader !== undefined ? tpl.sacredHeader : current.sacredHeader,
    titleDecoration: tpl.titleDecoration,
  };
}
